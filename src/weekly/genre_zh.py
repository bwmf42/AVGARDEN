def _norm_key(text: str) -> str:
    t = (text or "").strip()
    t = t.replace("（", "(").replace("）", ")")
    t = re.sub(r"\s+", "", t)
    return t


def translate_genre(name: str) -> str:
    """Map one genre string to the canonical JavBus-aligned label."""
    raw = (name or "").strip()
    if not raw:
        return ""
    key = _norm_key(raw)
    if key in _GENRE_MAP:
        return _GENRE_MAP[key]
    low = key.lower()
    for k, v in _GENRE_MAP.items():
        if _norm_key(k).lower() == low:
            return v
    key2 = re.sub(r"\(.*?\)", "", key).strip()
    if key2 and key2 != key:
        if key2 in _GENRE_MAP:
            return _GENRE_MAP[key2]
        for k, v in _GENRE_MAP.items():
            if _norm_key(k).lower() == key2.lower():
                return v
    # already Chinese / mixed site tag: keep as-is (do not invent simplified)
    return raw


def translate_genres(genres: Iterable[str]) -> List[str]:
    """Translate/normalize and de-dupe, preserve order."""
    out: List[str] = []
    seen = set()
    for g in genres or []:
        zh = translate_genre(g)
        if not zh or zh in seen:
            continue
        seen.add(zh)
        out.append(zh)
    return out


def merge_genres(*lists: Iterable[str]) -> List[str]:
    """Merge genre lists, normalize, de-dupe."""
    combined = []
    for lst in lists:
        if not lst:
            continue
        for g in lst:
            if g:
                combined.append(str(g))
    return translate_genres(combined)
