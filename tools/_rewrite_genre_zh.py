def main() -> None:
    text = PATH.read_text(encoding="utf-8")
    m = re.search(r"(_GENRE_MAP = \{)(.*?)(\n\})", text, re.S)
    if not m:
        raise SystemExit("map not found")
    body = m.group(2)

    def repl(mo: re.Match) -> str:
        key, val = mo.group(1), mo.group(2)
        newv = simp(val)
        if newv in VALUE_SEMANTIC:
            newv = VALUE_SEMANTIC[newv]
        if key in KEY_OVERRIDES:
            newv = KEY_OVERRIDES[key]
        return f'"{key}": "{newv}"'

    new_body = re.sub(r'"([^"]+)":\s*"([^"]*)"', repl, body)
    if '"小柄"' not in new_body:
        new_body = '\n    "小柄": "娇小",' + new_body

    text = text[: m.start(2)] + new_body + text[m.end(2) :]

    old_doc = (
        '"""MGS 日文ジャンル → 与库内 JavBus 标签对齐的名称。\n\n'
        "目标：屏蔽/收藏沿用 weekly 里已有字符串，不另起一套简体新标签。\n"
        "- JavBus 已有的繁体/中文标签：原样通过（可做别名归一到主名）\n"
        "- MGS 日文：映射到同义的 JavBus 名\n"
        "- NTR 固定为 NTR（用户要求不变）\n"
        '"""'
    )
    new_doc = (
        '"""MGS/DMM 日文ジャンル → 大陆简体；JavBus 中文标签繁→简。\n\n'
        "- JavBus/已有中文：只做繁体转简体，不另起一套说法\n"
        "- MGS/DMM 日文与英文：按大陆常用理解翻译（如 小柄→娇小）\n"
        "- NTR 固定为 NTR\n"
        "- 最终 snap 到 blocked_genres.txt 精确拼写（Go 过滤用）\n"
        '"""'
    )
    if old_doc in text:
        text = text.replace(old_doc, new_doc)

    fold_items = ",\n    ".join(f'"{k}": "{v}"' for k, v in sorted(_FOLD.items()))
    new_fold = (
        "# 繁→简（展示与屏蔽 fold 共用，无外部依赖）\n"
        f"_FOLD_CHARS = str.maketrans({{\n    {fold_items}\n}})\n\n\n"
        "def _to_simplified(text: str) -> str:\n"
        '    """Character-level 繁体→简体 for genre labels."""\n'
        "    return (text or \"\").translate(_FOLD_CHARS)\n"
    )
    old_fold_pat = re.compile(
        r"# Minimal 繁简 folding.*?\n_FOLD_CHARS = str\.maketrans\(\{.*?\}\)\n",
        re.S,
    )
    if not old_fold_pat.search(text):
        raise SystemExit("fold block not found")
    text = old_fold_pat.sub(new_fold + "\n", text)

    old_tr = (
        "    elif not _looks_japanese(raw):\n"
        "        out = raw\n"
        "    else:\n"
        "        # unknown Japanese: leave as-is until mapped into static/memory\n"
        "        out = raw\n"
        "    snapped = snap_to_blocked(out)\n"
        "    if snapped != out:\n"
        "        remember(raw, snapped)\n"
        "    return snapped"
    )
    new_tr = (
        "    elif not _looks_japanese(raw):\n"
        "        out = raw\n"
        "    else:\n"
        "        # unknown Japanese: leave as-is until mapped into static/memory\n"
        "        out = raw\n"
        "    # JavBus 繁体等中文标签统一简体；map/memory 已是简体则不变\n"
        "    if not _looks_japanese(out):\n"
        "        out = _to_simplified(out)\n"
        "    snapped = snap_to_blocked(out)\n"
        "    if snapped != out:\n"
        "        remember(raw, snapped)\n"
        "    return snapped"
    )
    if old_tr not in text:
        raise SystemExit("translate block not found")
    text = text.replace(old_tr, new_tr)
    text = text.replace(
        "Order: static map → memory → original; finally align to user blocked list",
        "Order: static map → memory → original → 繁转简; finally align to user blocked list",
    )

    PATH.write_text(text, encoding="utf-8")
    print(f"rewrote {PATH} fold_size={len(_FOLD)}")


if __name__ == "__main__":
    main()
